/*
 * Слой 2: планировщик профилей.
 *
 * Превращает профиль скорости в таблицу пауз: p[i] - пауза (мкс) перед шагом i.
 * Генератор шагов (stepper.c) только читает эту таблицу, поэтому профиль
 * можно менять, не трогая прерывание.
 */
#pragma once

#include <stdint.h>

/*
 * Экспоненциальный профиль ГОСТ Р ИСО 26782-2016 (прил. C).
 *   положение:  x(t) = [1 - exp(-t/tau)] / D,  D = 1 - exp(-t_fev/tau)
 *   время шага i:  t(i) = -tau * ln(1 - (i/n) * D)
 *
 * min_period_us  - не чаще этого (ограничение по скорости шагов)
 * accel_sps2     - ограничение ускорения, шагов/с^2 (0 = выключено). Профиль ГОСТ
 *                  стартует сразу на максимальной скорости, шаговик так не может,
 *                  поэтому начало "смягчается", дальше профиль сам догоняет расписание.
 */
void profile_build_gost(uint32_t *p, uint32_t n, float tau, float t_fev,
                        uint32_t min_period_us, float accel_sps2);

/* Трапеция: разгон - постоянная скорость - торможение. Скорости в шагах/с. */
void profile_build_trapezoid(uint32_t *p, uint32_t n, float vmax, float accel, float vstart);
