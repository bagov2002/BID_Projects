/*
 * Слой 1: генератор шагов.
 *
 * Концевик - главный, а не счётчик шагов. Обе функции запуска едут в заданную
 * сторону, пока не сработает концевик stop_pin. Если он не сработал за max_steps
 * шагов - это авария (обрыв концевика, не тот тип контакта, механическое
 * заклинивание или мотор теряет шаги), а не нормальный конец движения.
 *
 * Для stepper_run_table: periods_us задаёт ФОРМУ скорости (разгон/торможение) на
 * первых table_len шагах. Если концевик к этому моменту ещё не сработал, движение
 * НЕ останавливается - оно продолжается на последней (самой медленной,
 * "крейсерской") паузе из таблицы, пока концевик не сработает или не будет
 * превышен max_steps. Так безопаснее: даже если реальное расстояние между
 * концевиками из-за проскальзывания чуть отличается от расчёта, мотор всё равно
 * доедет и остановится именно на концевике, а не "зависнет" на полпути.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

typedef enum {
    STEPPER_IDLE,            /* ещё не запускали */
    STEPPER_RUNNING,         /* идёт движение */
    STEPPER_DONE_LIMIT,      /* нормальный исход: доехали до концевика */
    STEPPER_SAFETY_STOP,     /* авария: концевик не сработал за max_steps шагов */
} stepper_state_t;

void stepper_init(void);

/*
 * Движение по таблице periods_us[0..table_len-1] (пауза перед шагом i), а после
 * её конца - на последней паузе таблицы, пока не сработает stop_pin.
 * max_steps - предохранитель, должен быть заметно больше table_len (например,
 * в 2 раза), иначе он сработает раньше времени на нормальном ходе.
 * Таблица должна жить до конца движения.
 */
void stepper_run_table(bool forward, const uint32_t *periods_us, uint32_t table_len,
                        uint32_t max_steps, int stop_pin);

/* Движение с постоянным периодом, пока не сработает концевик (или до max_steps). Для калибровки. */
void stepper_run_const(bool forward, uint32_t period_us, uint32_t max_steps, int stop_pin);

/* Дождаться конца движения, вернуть причину остановки. */
stepper_state_t stepper_wait(void);

/* Сколько шагов сделано в последнем движении. */
uint32_t stepper_steps_done(void);

/* Текущая позиция в микрошагах (вперёд +, назад -). */
int32_t stepper_position(void);

/* Сработал ли концевик (сейчас). */
bool stepper_limit_hit(int pin);
